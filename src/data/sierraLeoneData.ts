import { projectLngLat, PROVINCE_GEOJSON, ringsToSvgPath } from './sierraLeoneGeoJson';

export type RegionId = 'western' | 'northern' | 'southern' | 'eastern' | 'north-west';

export interface PlaceItem {
  name: string;
  category: string;
  description: string;
}

export interface CityData {
  id: string;
  name: string;
  regionId: RegionId;
  regionName: string;
  status: 'Country Capital' | 'Province Capital' | 'District Capital' | 'Major Town';
  isMajor: boolean;
  population: string;
  populationNum: number;
  knownFor: string;
  about: string;
  mapX: number; // Projected from real GPS (lng, lat) into 850 x 1024 map space
  mapY: number;
  lat: number; // WGS84 Latitude (degrees North)
  lng: number; // WGS84 Longitude (degrees West, negative)
  labelDx?: number;
  labelDy?: number;
  labelAnchor?: 'start' | 'middle' | 'end';
  photoUrl?: string;
  landscapeTheme: 'coastal' | 'highlands' | 'savanna' | 'rainforest' | 'riverine';
  keyFacts: {
    district: string;
    elevation: string;
    established: string;
    climate: string;
    area: string;
    languages: string;
  };
  places: PlaceItem[];
  moreInfo: {
    economy: string;
    transport: string;
    education: string;
    culturalNote: string;
  };
  siblingCityIds?: string[];
}

